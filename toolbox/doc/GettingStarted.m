%[text] # Get started with Color Beats Challenge
%[text] Turn sound into a colorful picture. You can use the included piano scales without a microphone, or record your own voice.
%[text] ## Open the activity
%[text] Type `openColorBeatsChallenge` in the MATLAB Command Window and press Enter. The student activity opens in the Live Editor with instructions, sliders, and buttons.
%[text] You can also open `ColorBeatsChallenge_Student_Activity.m` from the activity files. The `.m` file is a live script: it contains both a lesson and MATLAB code.
%[text] ## Try the piano sample
%[text] 1. Leave **Audio source** set to **Sample audio** and press **Choose audio source**.
%[text] 2. In Part 1, press **Build the rainbow!**
%[text] 3. In Part 2, press **Load or record my sound!**
%[text] 4. Continue through Parts 3 to 5. Change the sliders and press each section's button to see what happens. \
%[text] ## Try your own voice
%[text] In the activity's Get Started section, choose **Computer** from the Audio source menu and press **Choose audio source**. Select your microphone. In Part 2, choose a recording duration and press **Load or record my sound!** Speak, sing, whistle, or hum after the countdown. Then run the remaining parts again.
%[text] For a phone or tablet, choose **Mobile device** and follow the activity's MATLAB Mobile instructions. Microphone permission is required only when recording.
%[text] ## Try the app
%[text] On MATLAB Desktop or MATLAB Online in a computer browser, type `ColorBeatsApp` in the Command Window. Choose **Demo Sound** to load the piano scales. The app is optional; the student activity contains the full lesson.
%[text] ## Teacher guide
%[text] Open [Color Beats Challenge Activity Guide.pdf](<Color Beats Challenge Activity Guide.pdf>) in this folder for teaching ideas. The guide's earlier microphone-only instructions also work with the sample-audio alternative described in the updated student activity.

